/**
 * MCP Streamable HTTP composition root.
 *
 * Configuration comes from the environment only:
 *
 *   INVOKTA_HTTP_HOST             bind host (default 127.0.0.1)
 *   INVOKTA_HTTP_PORT, PORT       bind port (default 3000); the Invokta-specific
 *                                   name wins when both are set
 *   INVOKTA_HTTP_ALLOWED_HOSTS    comma-separated Host allowlist, required
 *                                   for non-loopback exclusive Bearer
 *                                   deployments; OAuth derives it from the
 *                                   public URL, including when a static bearer
 *                                   token is also configured
 *   INVOKTA_HTTP_ALLOWED_ORIGINS  comma-separated browser origin allowlist
 *   INVOKTA_HTTP_MAX_BODY_BYTES   request body limit (adapter default 1 MiB)
 *
 * An invalid value aborts startup rather than falling back to a default, and
 * every diagnostic goes to stderr without any value.
 *
 * Generated by "invokta-deploy init". This file is yours to edit.
 */
// Keep this import first and on its own: importing the loader applies the
// environment file, and nothing below may read configuration before it has.
import "./env.js";

import { serveMcpHttp } from "@invokta/mcp";

import {
  EngineStartupError,
  reportStartupFailure,
  requireEnvironment,
} from "./env.js";
import { requireDatabaseConfiguration } from "./database/config.js";

const requiredEnvironmentNames = [
  "OPENROUTER_API_KEY",
] as const;

const defaultHost = "127.0.0.1";
const defaultPort = 3000;
const maximumPort = 65_535;
const loopbackHosts = new Set(["127.0.0.1", "localhost", "::1", "[::1]"]);
const nulCharacter = "\u0000";

function readValue(name: string): string | undefined {
  const value = process.env[name];
  if (value === undefined) return undefined;
  if (value === "") {
    throw new EngineStartupError(`${name} must not be empty.`);
  }
  if (value.includes(nulCharacter)) {
    throw new EngineStartupError(`${name} must not contain a NUL character.`);
  }
  return value;
}

/** Splits on commas, trims every item, and drops the empty ones. */
function readList(name: string): readonly string[] | undefined {
  const value = readValue(name);
  if (value === undefined) return undefined;
  const items = value
    .split(",")
    .map((item) => item.trim())
    .filter((item) => item !== "");
  if (items.length === 0) {
    throw new EngineStartupError(`${name} must list at least one entry.`);
  }
  return items;
}

function readInteger(
  name: string,
  minimum: number,
  maximum: number,
): number | undefined {
  const value = readValue(name);
  if (value === undefined) return undefined;
  const parsed = /^[0-9]+$/.test(value) ? Number(value) : Number.NaN;
  if (!Number.isSafeInteger(parsed) || parsed < minimum || parsed > maximum) {
    throw new EngineStartupError(
      `${name} must be an integer between ${minimum} and ${maximum}.`,
    );
  }
  return parsed;
}

async function main(): Promise<void> {
  requireEnvironment(requiredEnvironmentNames);
  requireDatabaseConfiguration();

  const { createHttpAuth, readHttpAuthenticationConfiguration } = await import(
    "./http-auth.js"
  );
  const authenticationConfiguration = readHttpAuthenticationConfiguration();

  const host = readValue("INVOKTA_HTTP_HOST") ?? defaultHost;
  const port =
    readInteger("INVOKTA_HTTP_PORT", 0, maximumPort) ??
    readInteger("PORT", 0, maximumPort) ??
    defaultPort;
  let allowedHosts = readList("INVOKTA_HTTP_ALLOWED_HOSTS");
  const allowedOrigins = readList("INVOKTA_HTTP_ALLOWED_ORIGINS");
  const maxRequestBodyBytes = readInteger(
    "INVOKTA_HTTP_MAX_BODY_BYTES",
    1,
    Number.MAX_SAFE_INTEGER,
  );

  // The adapter validates the raw Host header. OAuth owns a canonical public
  // resource URL, so its hostname provides a safe default for Compose. Static
  // Bearer deployments have no such source and must stay explicit.
  if (allowedHosts === undefined && !loopbackHosts.has(host)) {
    if (authenticationConfiguration.mode === "oauth") {
      allowedHosts = [
        new URL(authenticationConfiguration.resource).hostname,
        "engine",
        "localhost",
        "127.0.0.1",
      ];
    } else {
      throw new EngineStartupError(
        "INVOKTA_HTTP_ALLOWED_HOSTS is required when INVOKTA_HTTP_HOST is not a loopback address.",
      );
    }
  }

  // Constructed only after all adapter configuration has been validated. The
  // runtime owns the database lifecycle; this adapter owns only HTTP serving.
  const { createSecondBrainRuntime } = await import("./runtime.js");
  const httpAuth = createHttpAuth(authenticationConfiguration);
  const runtime = await createSecondBrainRuntime();

  let server: Awaited<ReturnType<typeof serveMcpHttp>>;
  try {
    server = await serveMcpHttp(runtime.engine, {
      host,
      port,
      ...(allowedHosts === undefined ? {} : { allowedHosts }),
      ...(allowedOrigins === undefined ? {} : { allowedOrigins }),
      ...(maxRequestBodyBytes === undefined ? {} : { maxRequestBodyBytes }),
      auth: httpAuth,
    });
  } catch (error) {
    await runtime.close();
    throw error;
  }

  let closing = false;
  const shutdown = (): void => {
    if (closing) return;
    closing = true;
    // The HTTP server aborts tracked requests before the database pool closes,
    // so no invocation can outlive its runtime dependencies.
    void (async () => {
      let failed = false;
      try {
        await server.close();
      } catch {
        failed = true;
      }
      try {
        await runtime.close();
      } catch {
        failed = true;
      }
      process.exit(failed ? 1 : 0);
    })();
  };
  // Registered before the announcement: the announcement is what tells a
  // supervisor the process is up, and a signal arriving before these handlers
  // exist would terminate it by default disposition instead of closing it.
  process.once("SIGTERM", shutdown);
  process.once("SIGINT", shutdown);
  if (runtime.restartRequested !== null) {
    void runtime.restartRequested.then(
      () => shutdown(),
      () => undefined,
    );
  }

  const address = server.address();
  process.stderr.write(
    `MCP endpoint: http://${address.host}:${address.port}/mcp\n`,
  );
}

try {
  await main();
} catch (error) {
  reportStartupFailure(error);
}
