import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  lstatSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { parseEnv } from "node:util";

const baseEnvironmentFile = ".env";
const developmentEnvironmentFile = ".env.development";
const projectName = "second-brain-dev";
const allowedActions = new Set([
  "bootstrap",
  "down",
  "logs",
  "prepare",
  "ps",
  "up",
]);

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

function readEnvironmentFile(path, required) {
  if (!existsSync(path)) {
    if (required) fail(`Create ${path} and set OPENROUTER_API_KEY first.`);
    return null;
  }
  const status = lstatSync(path);
  if (!status.isFile() || status.isSymbolicLink()) {
    fail(`${path} must be a regular file, not a symbolic link.`);
  }
  try {
    return parseEnv(readFileSync(path, "utf8"));
  } catch {
    fail(`${path} could not be parsed.`);
  }
}

function usableOpenRouterKey(environment) {
  const value = process.env.OPENROUTER_API_KEY ?? environment.OPENROUTER_API_KEY;
  return (
    typeof value === "string" &&
    value !== "" &&
    value !== "change-me" &&
    !value.startsWith("replace-with-")
  );
}

function createDevelopmentEnvironment() {
  const databasePassword = randomBytes(32).toString("base64url");
  const encryptionKey = randomBytes(32).toString("base64url");
  const content = [
    "# Generated by npm run dev:prepare. Local development only.",
    "POSTGRES_DB=second_brain_dev",
    "POSTGRES_USER=second_brain_dev",
    `POSTGRES_PASSWORD=${databasePassword}`,
    `DATABASE_URL=postgresql://second_brain_dev:${databasePassword}@127.0.0.1:55432/second_brain_dev`,
    "POSTGRES_BIND_ADDRESS=127.0.0.1",
    "POSTGRES_PORT=55432",
    `SECOND_BRAIN_CONFIG_ENCRYPTION_KEY=${encryptionKey}`,
    "SECOND_BRAIN_WORKER_ID=second-brain-development-worker",
    "SECOND_BRAIN_BIND_ADDRESS=127.0.0.1",
    "SECOND_BRAIN_HTTP_PORT=3000",
    "SECOND_BRAIN_OAUTH_PORT=3001",
    "SECOND_BRAIN_ADMIN_PORT=3002",
    "SECOND_BRAIN_DEV_PORT=8080",
    "SECOND_BRAIN_IMAGE=second-brain-dev",
    "SECOND_BRAIN_IMAGE_TAG=local",
    "INVOKTA_HTTP_AUTH_MODE=oauth",
    "INVOKTA_HTTP_BEARER_TOKEN=",
    "INVOKTA_HTTP_PRINCIPAL_ID=",
    "",
  ].join("\n");
  writeFileSync(developmentEnvironmentFile, content, {
    encoding: "utf8",
    flag: "wx",
    mode: 0o600,
  });
}

function validPort(value) {
  if (typeof value !== "string" || !/^[1-9][0-9]{0,4}$/u.test(value)) {
    return false;
  }
  const parsed = Number(value);
  return Number.isSafeInteger(parsed) && parsed <= 65_535;
}

function validateDevelopmentEnvironment(environment) {
  for (const name of [
    "POSTGRES_DB",
    "POSTGRES_USER",
    "POSTGRES_PASSWORD",
    "SECOND_BRAIN_CONFIG_ENCRYPTION_KEY",
    "SECOND_BRAIN_DEV_PORT",
  ]) {
    if (environment[name] === undefined || environment[name] === "") {
      fail(`${developmentEnvironmentFile} is missing ${name}.`);
    }
  }
  if (!validPort(environment.SECOND_BRAIN_DEV_PORT)) {
    fail(`${developmentEnvironmentFile} contains an invalid SECOND_BRAIN_DEV_PORT.`);
  }
  const encryptionKey = environment.SECOND_BRAIN_CONFIG_ENCRYPTION_KEY;
  const decoded = Buffer.from(encryptionKey, "base64url");
  if (decoded.length !== 32 || decoded.toString("base64url") !== encryptionKey) {
    fail(
      `${developmentEnvironmentFile} contains an invalid SECOND_BRAIN_CONFIG_ENCRYPTION_KEY.`,
    );
  }
}

function prepare() {
  const base = readEnvironmentFile(baseEnvironmentFile, true);
  if (!usableOpenRouterKey(base)) {
    fail(`Set a non-placeholder OPENROUTER_API_KEY in ${baseEnvironmentFile}.`);
  }
  if (!existsSync(developmentEnvironmentFile)) {
    createDevelopmentEnvironment();
  }
  const development = readEnvironmentFile(developmentEnvironmentFile, true);
  chmodSync(developmentEnvironmentFile, 0o600);
  validateDevelopmentEnvironment(development);
  return { base, development };
}

function requireDocker() {
  const result = spawnSync(
    "docker",
    ["info", "--format", "{{.ServerVersion}}"],
    { stdio: "ignore" },
  );
  if (result.status !== 0) {
    fail(
      "Docker is unavailable. Start Docker Desktop and enable its WSL integration, then rerun npm run dev.",
    );
  }
}

function composeArguments(development) {
  const publicOrigin = `http://127.0.0.1:${development.SECOND_BRAIN_DEV_PORT}`;
  const environment = {
    ...process.env,
    ...development,
    SECOND_BRAIN_PUBLIC_URL: publicOrigin,
    SECOND_BRAIN_PUBLIC_HOST: "127.0.0.1",
  };
  const common = [
    "compose",
    "--project-name", projectName,
    "--env-file", baseEnvironmentFile,
    "--env-file", developmentEnvironmentFile,
    "--file", "compose.yaml",
    "--file", "compose.dev.yaml",
  ];
  return { common, environment, publicOrigin };
}

function runCompose(arguments_, environment) {
  const result = spawnSync("docker", arguments_, {
    env: environment,
    stdio: "inherit",
  });
  if (result.status !== 0) fail("The local Docker Compose command failed.");
}

const action = process.argv[2] ?? "up";
if (!allowedActions.has(action)) {
  fail("Usage: node tools/local-dev.mjs <up|bootstrap|logs|ps|down|prepare>.");
}

const { development } = prepare();
if (action === "prepare") {
  process.stdout.write(
    `${developmentEnvironmentFile} is ready with local-only credentials.\n`,
  );
  process.exit(0);
}

requireDocker();
const { common, environment, publicOrigin } = composeArguments(development);

switch (action) {
  case "up":
    runCompose([...common, "up", "--detach", "--build"], environment);
    process.stdout.write(
      `Second Brain is starting and will be available at ${publicOrigin}/admin/.\n`,
    );
    process.stdout.write(
      "For a new local database, finish the one-time owner setup with npm run dev:bootstrap.\n",
    );
    break;
  case "bootstrap":
    runCompose(
      [
        ...common,
        "up",
        "--detach",
        "--build",
        "--wait",
        "postgres",
        "migrate",
        "auth",
      ],
      environment,
    );
    runCompose(
      [...common, "run", "--rm", "auth", "node", "dist/services/auth/bootstrap-account.js"],
      environment,
    );
    runCompose([...common, "up", "--detach", "--wait"], environment);
    process.stdout.write(`Second Brain is ready at ${publicOrigin}/admin/.\n`);
    break;
  case "logs":
    runCompose([...common, "logs", "--follow", "--tail", "100"], environment);
    break;
  case "ps":
    runCompose([...common, "ps"], environment);
    break;
  case "down":
    runCompose([...common, "down", "--remove-orphans"], environment);
    break;
  default:
    fail("Unsupported local development action.");
}
